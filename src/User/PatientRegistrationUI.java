    private void btnRegistorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistorActionPerformed
        //To Add Patient Button Option
        if (checkVal()){

            try {
                String patientID = txtPatientID.getText();

                // Check Duplicate Patient ID
                if (list.DuplicatePatientID(patientID)) {
                    JOptionPane.showMessageDialog(this, "Patient ID already exists!");
                    txtPatientID.setText("");
                    txtName.setText("");
                    txtAge.setText("");
                    txtIllness.setText("");
                    txtcheckInTime.setText("");
                    rdoNormal.setSelected(false);
                    rdoSerious.setSelected(false);
                    rdoCritical.setSelected(false);
                    return; 
                }

                String Name = txtName.getText();
                
                int Age;
                
                try {
                    Age = Integer.parseInt(txtAge.getText());
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Invalid Age!");
                    return;
                }

                String IllString = txtIllness.getText();

                String severity="";
                if(rdoNormal.isSelected()) {
                    severity="Normal";
                } else if (rdoSerious.isSelected()){
                    severity="Serious";
                } else if (rdoCritical.isSelected()) {
                    severity = "Critical";
                } else {
                    JOptionPane.showMessageDialog(this, "Please select severity level");
                    return;
                }

                String checkInTime = txtcheckInTime.getText();

                list.insertLast(patientID, Name, Age, IllString, severity, checkInTime);
                PatientFileDB.savePatient(patientID, Name, Age, IllString, severity, checkInTime);

                JOptionPane.showMessageDialog(this, "Data Inserted Successfully!");

                txtPatientID.setText("");
                txtName.setText("");
                txtAge.setText("");
                txtIllness.setText("");
                txtcheckInTime.setText("");
                rdoNormal.setSelected(false);
                rdoSerious.setSelected(false);
                rdoCritical.setSelected(false);

            } catch (NumberFormatException e) {
                txtPatientID.setText("");
                txtName.setText("");
                txtAge.setText("");
                txtIllness.setText("");
                txtcheckInTime.setText("");
                rdoNormal.setSelected(false);
                rdoSerious.setSelected(false);
                rdoCritical.setSelected(false);
            }
        }
    }//GEN-LAST:event_btnRegistorActionPerformed

    private void btnDisplayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDisplayActionPerformed
        DefaultTableModel model = (DefaultTableModel) PRTable.getModel();

        model.setRowCount(0);

        Link current = list.getFirst();

        while(current != null){

            model.addRow(new Object[]{
                current.patientId,
                current.name,
                current.age,
                current.illness,
                current.severity,
                current.checkInTime                                                       
            });

        current = current.next;
        }
    }//GEN-LAST:event_btnDisplayActionPerformed

