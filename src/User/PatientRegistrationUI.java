    private boolean checkVal(){
        
        if (txtPatientID.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Patient ID cannot be blank");
            return false;
        }
        if (txtName.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Name cannot be blank");
            return false;
        }
        if (txtAge.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Age cannot be blank");
            return false;
        }
        if (txtIllness.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Illness cannot be blank");
            return false;
        }
        if (txtcheckInTime.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Check-in time cannot be blank");
            return false;
        }
        return true;
    }

