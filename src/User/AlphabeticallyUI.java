    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
            try {

            File file = new File("PatientRegistration.txt"); // change path if needed
            Scanner sc = new Scanner(file);

            QuickSortByAlphabetically sorter = new QuickSortByAlphabetically(100);

            while (sc.hasNextLine()) {
                String line = sc.nextLine();
                Patient p = Patient.fromCSV(line);
                sorter.insert(p);
            }

            sc.close();

            // sort alphabetically by name
            sorter.quickSort();

            // load into table
            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new String[]{
                "ID", "Name", "Age", "Illness", "Severity", "CheckIn"
            });

            for (int i = 0; i < sorter.size(); i++) {
                Patient p = sorter.getArray()[i];

                model.addRow(new Object[]{
                    p.getPatientId(),
                    p.getName(),
                    p.getAge(),
                    p.getIllness(),
                    p.getSeverity(),
                    p.getCheckInTime()
                });
            }

            tblAlphabetically.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

